CREATE TABLE IF NOT EXISTS ALIMENTO (
    ID_ALIMENTO INTEGER PRIMARY KEY,
    NOMBRE VARCHAR(160) NOT NULL,
    TIPO VARCHAR(80) NOT NULL,
    DESCRIPCION VARCHAR(1000) NOT NULL,
    CANTIDAD_EN_STOCK INTEGER NOT NULL CHECK (CANTIDAD_EN_STOCK >= 0),
    PRECIO_UNITARIO DECIMAL(12, 2) NOT NULL CHECK (PRECIO_UNITARIO >= 0)
);

CREATE INDEX IF NOT EXISTS IDX_ALIMENTO_TIPO ON ALIMENTO (TIPO);

CREATE TABLE IF NOT EXISTS MESA (
    ID_MESA INTEGER PRIMARY KEY,
    RESERVADA BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS RESERVA (
    ID_RESERVA INTEGER PRIMARY KEY,
    FECHA_CREACION DATE NOT NULL,
    FRANJA_HORARIA VARCHAR(80) NOT NULL,
    CODIGO_ESTUDIANTE VARCHAR(100),
    CEDULA_PROFESOR VARCHAR(100),
    CHECK (CODIGO_ESTUDIANTE IS NOT NULL OR CEDULA_PROFESOR IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS IDX_RESERVA_FECHA ON RESERVA (FECHA_CREACION);
CREATE INDEX IF NOT EXISTS IDX_RESERVA_ESTUDIANTE ON RESERVA (CODIGO_ESTUDIANTE);
CREATE INDEX IF NOT EXISTS IDX_RESERVA_PROFESOR ON RESERVA (CEDULA_PROFESOR);
CREATE INDEX IF NOT EXISTS IDX_RESERVA_FRANJA ON RESERVA (FRANJA_HORARIA);

CREATE TABLE IF NOT EXISTS RESERVA_MESA (
    ID_RESERVA INTEGER NOT NULL,
    ID_MESA INTEGER NOT NULL UNIQUE,
    PRIMARY KEY (ID_RESERVA, ID_MESA),
    CONSTRAINT FK_RESERVA_MESA_RESERVA
        FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA (ID_RESERVA) ON DELETE CASCADE,
    CONSTRAINT FK_RESERVA_MESA_MESA
        FOREIGN KEY (ID_MESA) REFERENCES MESA (ID_MESA) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS TICKET (
    ID_TICKET INTEGER PRIMARY KEY,
    FECHA_GENERACION TIMESTAMP NOT NULL,
    VALIDO BOOLEAN NOT NULL,
    CODIGO_QR BLOB
);

CREATE INDEX IF NOT EXISTS IDX_TICKET_VALIDO ON TICKET (VALIDO);

CREATE TABLE IF NOT EXISTS FACTURA (
    ID_FACTURA VARCHAR(100) PRIMARY KEY,
    FECHA DATE NOT NULL,
    NUMERO_PEDIDO INTEGER NOT NULL,
    METODO_PAGO VARCHAR(80) NOT NULL,
    TOTAL DECIMAL(12, 2) NOT NULL CHECK (TOTAL >= 0),
    DESCUENTO DECIMAL(12, 2) NOT NULL CHECK (DESCUENTO >= 0)
);

CREATE INDEX IF NOT EXISTS IDX_FACTURA_METODO ON FACTURA (METODO_PAGO);
CREATE INDEX IF NOT EXISTS IDX_FACTURA_FECHA ON FACTURA (FECHA);

CREATE TABLE IF NOT EXISTS FACTURA_TICKET (
    ID_FACTURA VARCHAR(100) PRIMARY KEY,
    ID_TICKET INTEGER NOT NULL UNIQUE,
    CONSTRAINT FK_FACTURA_TICKET_FACTURA
        FOREIGN KEY (ID_FACTURA) REFERENCES FACTURA (ID_FACTURA) ON DELETE CASCADE,
    CONSTRAINT FK_FACTURA_TICKET_TICKET
        FOREIGN KEY (ID_TICKET) REFERENCES TICKET (ID_TICKET) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS LINEA_FACTURA (
    NUM_LINEA_COMPRA INTEGER PRIMARY KEY,
    CANTIDAD INTEGER NOT NULL CHECK (CANTIDAD > 0),
    PRECIO_UNITARIO DECIMAL(12, 2) NOT NULL CHECK (PRECIO_UNITARIO >= 0),
    SUBTOTAL_ALIMENTO DECIMAL(12, 2) NOT NULL CHECK (SUBTOTAL_ALIMENTO >= 0)
);

CREATE TABLE IF NOT EXISTS REPORTE (
    ID_REPORTE VARCHAR(100) PRIMARY KEY,
    FECHA_GENERACION DATE NOT NULL,
    FRANJA_HORARIA VARCHAR(80) NOT NULL,
    GRAFICOS BOOLEAN NOT NULL,
    DESCRIPCION VARCHAR(2000) NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_REPORTE_FECHA ON REPORTE (FECHA_GENERACION);
CREATE INDEX IF NOT EXISTS IDX_REPORTE_FRANJA ON REPORTE (FRANJA_HORARIA);
